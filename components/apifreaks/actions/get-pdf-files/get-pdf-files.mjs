import app from "../../apifreaks.app.mjs";

export default {
  key: "apifreaks-get-pdf-files",
  name: "Get List of PDF Files",
  description: "This API retrieves a list of all PDF files uploaded and generated by a specific user. Please note that if the user is part of an organization, only the Organization Administrator can access this endpoint. Organization Members cannot access this endpoint. [See the documentation](https://apifreaks.com/docs).",
  version: "0.0.1",
  type: "action",
  props: {
    app,

  },
  async run({ $ }) {
    const response = await this.app._makeRequest({
      $,
      method: "GET",
      path: "/v1.0/pdf/files",
    });
    $.export("$summary", "Successfully executed Get List of PDF Files");
    return response;
  },
};
