import smartsheet from "../../smartsheet.app.mjs";

export default {
  key: "smartsheet-create-discussion",
  name: "Create Discussion",
  description:
    "Creates a discussion on a Smartsheet sheet. If a Row ID is provided the discussion is attached to that row"
    + " (POST /sheets/{sheetId}/rows/{rowId}/discussions); otherwise it is created at the sheet level"
    + " (POST /sheets/{sheetId}/discussions). Use **List Sheets** to find a Sheet ID and **Get Row** to find a Row ID."
    + " The discussion title is auto-generated by Smartsheet from the first 100 characters of the initial comment"
    + " and cannot be set directly."
    + " [See the documentation](https://developers.smartsheet.com/api/smartsheet/openapi/discussions/discussions-create).",
  version: "0.0.1",
  type: "action",
  ai: "optimized",
  annotations: {
    readOnlyHint: false,
    destructiveHint: false,
    openWorldHint: true,
  },
  props: {
    smartsheet,
    sheetId: {
      propDefinition: [
        smartsheet,
        "sheetIdOrUrl",
      ],
      description:
        "The sheet on which to create the discussion. Accepts a numeric sheet ID (e.g. `1234567890123456`), or a"
        + " Smartsheet sheet URL, which is resolved to the ID for you. Use **List Sheets** to enumerate sheets.",
    },
    rowId: {
      type: "string",
      label: "Row ID",
      description:
        "Optional. The ID of the row to attach the discussion to (e.g. `9876543210123456`). If provided, the"
        + " discussion is created at the row level; if omitted, it is created at the sheet level. Run the"
        + " **Get Row** action to obtain a valid row ID.",
      optional: true,
    },
    commentText: {
      propDefinition: [
        smartsheet,
        "commentText",
      ],
      description:
        "The text of the initial comment that starts the discussion."
        + " Example: `This row needs review before Friday.` — the call returns the new discussion's ID and title"
        + " (auto-generated from this comment's text).",
    },
  },
  async run({ $ }) {
    const sheetId = await this.smartsheet.resolveSheetId(this.sheetId, {
      $,
    });

    const data = {
      comment: {
        text: this.commentText,
      },
    };

    const response = this.rowId
      ? await this.smartsheet.createRowDiscussion(sheetId, this.rowId, {
        $,
        data,
      })
      : await this.smartsheet.createDiscussion(sheetId, {
        $,
        data,
      });

    $.export("$summary", `Created discussion ${response.id} on sheet ${sheetId}`);
    return response;
  },
};
