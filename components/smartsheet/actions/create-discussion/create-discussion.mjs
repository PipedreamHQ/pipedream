import smartsheet from "../../smartsheet.app.mjs";

export default {
  key: "smartsheet-create-discussion",
  name: "Create Discussion",
  description:
    "Creates a discussion on a Smartsheet sheet. If a Row ID is provided the discussion is attached to that row"
    + " (POST /sheets/{sheetId}/rows/{rowId}/discussions); otherwise it is created at the sheet level"
    + " (POST /sheets/{sheetId}/discussions). Use **List Sheets** to find a Sheet ID and **Get Row** to find a Row ID."
    + " The discussion title is auto-generated by Smartsheet from the first 100 characters of the initial comment"
    + " and cannot be set directly."
    + " [See the documentation](https://developers.smartsheet.com/api/smartsheet/openapi/discussions/discussions-create).",
  version: "0.0.1",
  type: "action",
  annotations: {
    readOnlyHint: false,
    destructiveHint: false,
    openWorldHint: true,
  },
  props: {
    smartsheet,
    sheetId: {
      propDefinition: [
        smartsheet,
        "sheetId",
      ],
      description:
        "The ID of the sheet on which to create the discussion. Run the **List Sheets** action first to obtain a valid"
        + " sheet ID. Free-form string (IDs are 64-bit numeric; use a string to avoid precision loss).",
    },
    rowId: {
      propDefinition: [
        smartsheet,
        "rowId",
      ],
      description:
        "Optional. The ID of the row to attach the discussion to. If provided, the discussion is created at the row"
        + " level; if omitted, it is created at the sheet level. Run the **Get Row** action to obtain a valid row ID.",
      optional: true,
    },
    commentText: {
      type: "string",
      label: "Comment Text",
      description:
        "The text of the initial comment that starts the discussion."
        + " Example: `This row needs review before Friday.` — the call returns the new discussion's ID and title"
        + " (auto-generated from this comment's text).",
    },
  },
  async run({ $ }) {
    const data = {
      comment: {
        text: this.commentText,
      },
    };

    const response = this.rowId
      ? await this.smartsheet.createRowDiscussion(this.sheetId, this.rowId, {
        $,
        data,
      })
      : await this.smartsheet.createDiscussion(this.sheetId, {
        $,
        data,
      });

    $.export("$summary", `Created discussion ${response.id} on sheet ${this.sheetId}`);
    return response;
  },
};
